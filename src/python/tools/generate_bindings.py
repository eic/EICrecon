"""Generate one pybind11 binding module per C++ plugin with InitPlugin wiring.

For src/detectors/<P>/<P>.cc and src/global/<P>/<P>.cc this writes
src/python/bindings/plugins/<P>.cc, which binds every JOmniFactory type that the plugin wires,
with the plugin's own #include lines (so it compiles against the same headers and links the
same libraries, see src/python/CMakeLists.txt). Run from the repository root:

    python3 src/python/tools/generate_bindings.py

The output is committed; rerun when a plugin starts using a new factory type.
"""

import glob
import os
import re
import sys

HEADER = """\
// SPDX-License-Identifier: LGPL-3.0-or-later
// Copyright (C) 2026 Wouter Deconinck
//
// GENERATED by src/python/tools/generate_bindings.py from {source}: do not edit.
//
// Factory types wired by the {plugin} plugin, for eicrecon.plugins.{module}.
"""


def plugin_name(source_path):
    """Plugin name: set(PLUGIN_NAME ...) in the CMakeLists.txt, else the directory name"""
    d = os.path.dirname(source_path)
    cmake = os.path.join(d, "CMakeLists.txt")
    if os.path.exists(cmake):
        m = re.search(r'^\s*set\(PLUGIN_NAME\s+"?([\w-]+)"?\)', open(cmake).read(), re.M)
        if m:
            return m.group(1)
    return os.path.basename(d)


def plugin_sources(root="."):
    for pattern in ("src/detectors/*/*.cc", "src/global/*/*.cc"):
        for path in sorted(glob.glob(os.path.join(root, pattern))):
            text = open(path).read()
            if "InitPlugin" in text and "JOmniFactoryGeneratorT<" in text:
                yield path, text


def guards_at(text, pos, start):
    """Conditional-compilation lines (#if.../#elif/#else) that are open at `pos`, counting from
    `start` (guards opened before `start`, such as a whole-file guard, are not included)"""
    stack = []
    for line in text[start:pos].splitlines():
        s = line.strip()
        if s.startswith("#if"):
            stack.append([s])
        elif s.startswith(("#elif", "#else")) and stack:
            stack[-1].append(s)
        elif s.startswith("#endif") and stack:
            stack.pop()
    return [line for group in stack for line in group]


def generator_types(text):
    """All T in JOmniFactoryGeneratorT<T>, with balanced angle brackets, whitespace-normalized,
    and the conditional-compilation guards of their registration in InitPlugin (empty if any
    registration of T is unconditional)"""
    types, guards = [], {}
    start = text.index("InitPlugin")
    for m in re.finditer(r"JOmniFactoryGeneratorT\s*<", text):
        i, depth = m.end(), 1
        while depth:
            depth += {"<": 1, ">": -1}.get(text[i], 0)
            i += 1
        t = " ".join(text[m.end():i - 1].split())
        t = re.sub(r"\s*([<>,])\s*", r"\1", t).replace(",", ", ")
        guard = guards_at(text, m.start(), start) if m.start() > start else []
        if t not in types:
            types.append(t)
            guards[t] = guard
        elif not guard:
            guards[t] = []
    return types, guards


def python_name(cpp_type):
    """CalorimeterHitDigi_factory -> CalorimeterHitDigi;
    CollectionCollector_factory<edm4eic::Cluster, true> -> CollectionCollector_Cluster_true"""
    base, _, args = cpp_type.partition("<")
    base = base.split("::")[-1]
    base = base[: -len("_factory")] if base.endswith("_factory") else base
    if args:
        parts = [a.strip().split("::")[-1] for a in args.rstrip(">").split(",")]
        base += "_" + "_".join(re.sub(r"\W", "", p) for p in parts)
    return base


def module_name(plugin):
    return re.sub(r"\W", "_", plugin)


def preamble(text):
    """#include, using and conditional-compilation lines before InitPlugin"""
    head = text[: text.index("InitPlugin")]
    keep = []
    for line in head.splitlines():
        s = line.strip()
        if s.startswith(("#include", "#if", "#endif", "#else", "#elif", "using namespace")):
            keep.append(line)
    # drop a trailing unmatched '#if' (e.g. a guard closed after InitPlugin)
    depth = sum(1 for l in keep if l.strip().startswith("#if")) - sum(
        1 for l in keep if l.strip().startswith("#endif"))
    return keep, depth


def main():
    out_dir = "src/python/bindings/plugins"
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for path, text in plugin_sources():
        plugin = plugin_name(path)
        module = module_name(plugin)
        types, guards = generator_types(text)
        names = [python_name(t) for t in types]
        if len(set(names)) != len(names):
            sys.exit(f"{plugin}: Python names are not unique: {names}")
        lines, open_ifs = preamble(text)
        # using-directives anywhere in the file (often inside InitPlugin)
        for u in sorted(set(re.findall(r"using namespace [\w:]+;", text))):
            if u not in [l.strip() for l in lines]:
                lines.append(u)
        out = [HEADER.format(source=path, plugin=plugin, module=module)]
        out.append("#include <pybind11/pybind11.h>\n")
        out.append('#include "FactoryType.h"')
        out += lines
        out.append("")
        out.append("namespace py = pybind11;")
        out.append("using eicrecon::python::bind_factory;")
        out.append("")
        out.append(f"PYBIND11_MODULE(_wiring_{module}, m) {{")
        out.append(f'  m.doc() = "Factory types wired by the {plugin} plugin";')
        out.append('  py::module_::import("eicrecon._core");')
        for t, n in zip(types, names):
            # same guards as the registration in the plugin, so the binding compiles (and the
            # type is offered) exactly when the plugin wires it
            out += guards[t]
            out.append(f'  bind_factory<{t}>(m, "{n}");')
            out += ["#endif"] * sum(1 for g in guards[t] if g.startswith("#if"))
        extra = os.path.join(out_dir, f"{module}_extra.h")
        if os.path.exists(extra):
            # hand-written additions: C++ helpers for values Python cannot express
            out.insert(out.index("namespace py = pybind11;"), f'#include "plugins/{module}_extra.h"\n')
            # named per module: the binding modules share one process (RTLD_GLOBAL), so an
            # inline function of the same name in two of them would be an ODR violation
            out.append(f"  eicrecon_python_extra_{module}(m);")
        out.append("}")
        out += ["#endif"] * open_ifs
        target = os.path.join(out_dir, f"{module}.cc")
        with open(target, "w") as f:
            f.write("\n".join(out) + "\n")
        written.append((plugin, module, len(types)))
    with open(os.path.join(out_dir, "plugins.cmake"), "w") as f:
        f.write("# GENERATED by src/python/tools/generate_bindings.py: do not edit.\n")
        f.write("# <plugin> <module>\n")
        f.write("set(EICRECON_PYTHON_WIRING_PLUGINS\n")
        for plugin, module, _ in written:
            f.write(f"    {plugin} {module}\n")
        f.write(")\n")
    for plugin, module, n in written:
        print(f"{plugin:16s} -> _wiring_{module}: {n} factory types")


if __name__ == "__main__":
    main()
